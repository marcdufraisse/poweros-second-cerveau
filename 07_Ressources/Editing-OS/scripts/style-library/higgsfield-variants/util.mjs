/** Glass panel CSS for a .panel > .tilt structure (GSAP moves .panel, static
    3D tilt lives on .tilt). side: left | right. lit: light glass vs dark glass. */
export function glassCss(rootId, { side = "right", lit = false, top = 190, width = 560, pad = "44px 50px" }) {
  const tilt = side === "left" ? "var(--glass-tilt-l)" : "var(--glass-tilt)";
  const anchor = side === "left" ? `left: 120px;` : `right: 120px;`;
  return `      #${rootId} .panel { position: absolute; top: ${top}px; ${anchor} z-index: 3; }
      #${rootId} .tilt {
        width: ${width}px; padding: ${pad};
        display: flex; flex-direction: column; gap: 20px;
        background: ${lit ? "var(--glass-bg-lit)" : "var(--glass-bg)"};
        border: var(--glass-edge); border-radius: var(--radius);
        backdrop-filter: var(--glass-blur); -webkit-backdrop-filter: var(--glass-blur);
        box-shadow: var(--glass-shadow);
        transform: ${tilt};
      }`;
}

/** Entrance tween JS for a selector. kind: slide-side | rise | pop | blur */
export function entranceJs(sel, kind, side = "right", t = 0.1) {
  const x = side === "left" ? -90 : 90;
  switch (kind) {
    case "rise": return `      tl.from(root + " ${sel}", { autoAlpha: 0, y: 70, duration: 0.55, ease: "expo.out" }, ${t});`;
    case "pop": return `      tl.from(root + " ${sel}", { autoAlpha: 0, scale: 0.82, duration: 0.5, ease: "back.out(1.9)" }, ${t});`;
    case "blur": return `      tl.from(root + " ${sel}", { autoAlpha: 0, filter: "blur(14px)", duration: 0.6, ease: "power2.out" }, ${t});`;
    default: return `      tl.from(root + " ${sel}", { autoAlpha: 0, x: ${x}, duration: 0.55, ease: "expo.out" }, ${t});`;
  }
}

/** Drift-while-alive JS for a selector (the glass signature). */
export function driftJs(sel, { amp = 10, rot = 0.6, t = 0.7 } = {}) {
  return `      tl.to(root + " ${sel}", { y: ${-amp}, rotation: ${rot}, duration: 3, ease: "sine.inOut", yoyo: true, repeat: 1 }, ${t});`;
}

/** Hold to a total duration. */
export function holdJs(sec) {
  return `      tl.set({}, {}, ${sec});`;
}
