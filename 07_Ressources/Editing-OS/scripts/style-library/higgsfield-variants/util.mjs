// by composition id, tokens.css vars only, data-slot text, deterministic.

/** Seeded LCG — determinism rule: no Math.random anywhere in the pipeline. */
export function lcg(seed) {
  let s = seed >>> 0;
  return () => {
    s = (s * 1103515245 + 12345) % 2147483648;
    return s / 2147483648;
  };
}

/** Seeded shuffle (Fisher-Yates). */
export function shuffle(arr, rnd) {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/** Cartesian product of axis arrays: [{k:v},...] combos. */
export function combos(axes) {
  let out = [{}];
  for (const [key, values] of Object.entries(axes)) {
    const next = [];
    for (const base of out) for (const v of values) next.push({ ...base, [key]: v });
    out = next;
  }
  return out;
}

/** The standalone card HTML shell. js runs with `root` + `tl` predefined;
    it must add tweens to tl. Timeline is registered paused on window.__timelines. */
export function shell({ id, comment, css, body, js, depth = "../../.." }) {
  return `<!doctype html>
<!--
  HIGGSFIELD · generated variant · ${id}
  ${comment}
  GENERATED by scripts/style-library/gen-higgsfield-variants.mjs - do not hand-edit;
  edit the template family + re-run the generator.
-->
<html>
  <head>
    <meta charset="utf-8" />
    <link rel="stylesheet" href="${depth}/tokens.css" />
    <style>
      html, body { margin: 0; background: transparent; }
      #${id} {
        position: absolute; inset: 0; width: 1920px; height: 1080px;
        overflow: hidden; font-family: var(--font-display);
      }
${css}
    </style>
  </head>
  <body>
    <div id="${id}" data-composition-id="${id}" data-start="0" data-width="1920" data-height="1080">
${body}
    </div>

    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <script>
      window.__timelines = window.__timelines || {};
      const root = "#${id}";
      const cssv = getComputedStyle(document.documentElement);
      const LIME = cssv.getPropertyValue("--lime").trim();
      const LIMESOFT = cssv.getPropertyValue("--lime-soft").trim();
      const WHITE = cssv.getPropertyValue("--white").trim();
      function splitChars(el) {
        if (!el) return;
        const text = el.textContent; el.textContent = "";
        text.split("").forEach((ch) => {
          const s = document.createElement("span");
          s.className = "ch"; s.textContent = ch === " " ? "\\u00A0" : ch;
          el.appendChild(s);
        });
      }
      function seededOrder(n, seed) {
        let s = seed; const idx = Array.from({ length: n }, (_, i) => i);
        for (let i = n - 1; i > 0; i--) {
          s = (s * 1103515245 + 12345) % 2147483648;
          const j = s % (i + 1); [idx[i], idx[j]] = [idx[j], idx[i]];
        }
        const rank = new Array(n); idx.forEach((v, i) => (rank[v] = i)); return rank;
      }
      const tl = gsap.timeline({ paused: true });
${js}
      window.__timelines["${id}"] = tl;
    </script>
  </body>
</html>
`;
}

